  /**
   * @param {string} prefixCode  APZ, TR-PR, RS, …
   * @param {{ fullYear?: boolean, seqDigits?: number }} [idOpts]  RS: { fullYear: true, seqDigits: 4 }
   */
  function generateApplicationId(prefixCode, idOpts) {
    idOpts = idOpts || {};
    prefixCode = prefixCode || "TR";
    let year = new Date().getFullYear();
    let yy = String(year).slice(-2);
    let useFullYear = idOpts.fullYear === true;
    let seqDigits = idOpts.seqDigits != null ? idOpts.seqDigits : 3;
    let yearPart = useFullYear ? year : yy;
    let prefix = prefixCode + "-" + yearPart + "-";
    let legacyAlt = useFullYear ? prefixCode + "-" + yy + "-" : prefixCode + "-" + year + "-";
    let apps = loadApplications();
    let max = 0;
    for (let i = 0; i < apps.length; i++) {
      let id = apps[i].id;
      if (typeof id !== "string") continue;
      if (id.indexOf(prefix) === 0) {
        let num = parseInt(id.slice(prefix.length), 10);
        if (!isNaN(num) && num > max) max = num;
      } else if (!useFullYear && id.indexOf(legacyAlt) === 0) {
        let num = parseInt(id.slice(legacyAlt.length), 10);
        if (!isNaN(num) && num > max) max = num;
      } else if (useFullYear && id.indexOf(legacyAlt) === 0) {
        let num = parseInt(id.slice(legacyAlt.length), 10);
        if (!isNaN(num) && num > max) max = num;
      }
    }
    return prefix + String(max + 1).padStart(seqDigits, "0");
  }

