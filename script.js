  function initHeroSlider() {
    let root = $("#hero-slider");
    let track = $("#hero-slider-track");
    let btnPrev = $("#hero-slider-prev");
    let btnNext = $("#hero-slider-next");
    let dotsBox = $("#hero-slider-dots");
    if (!root || !track || !btnPrev || !btnNext || !dotsBox) return;

    let slides = $all(".hero-slider__slide", root);
    let n = slides.length;
    if (n === 0) return;

    let index = 0;
    let autoplayId = null;
    let touchStartX = null;
    let reduceMotion =
      typeof window.matchMedia === "function" && window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    function go(delta) {
      index = (index + delta + n) % n;
      render();
    }

    function goTo(i) {
      index = ((i % n) + n) % n;
      render();
    }

    function render() {
      track.style.transform = "translateX(-" + index * 100 + "%)";
      let dotButtons = dotsBox.querySelectorAll(".hero-slider__dot");
      for (let d = 0; d < dotButtons.length; d++) {
        let on = d === index;
        dotButtons[d].classList.toggle("is-active", on);
        dotButtons[d].setAttribute("aria-selected", on ? "true" : "false");
        dotButtons[d].setAttribute("tabindex", on ? "0" : "-1");
      }
      root.setAttribute("aria-live", "polite");
    }

    dotsBox.innerHTML = "";
    for (let i = 0; i < n; i++) {
      (function (idx) {
        let b = document.createElement("button");
        b.type = "button";
        b.className = "hero-slider__dot";
        b.setAttribute("role", "tab");
        b.setAttribute("aria-label", "Слайд " + (idx + 1) + " из " + n);
        b.addEventListener("click", function () {
          goTo(idx);
          restartAutoplay();
        });
        dotsBox.appendChild(b);
      })(i);
    }

    btnPrev.addEventListener("click", function () {
      go(-1);
      restartAutoplay();
    });
    btnNext.addEventListener("click", function () {
      go(1);
      restartAutoplay();
    });

    root.addEventListener(
      "keydown",
      function (e) {
        if (e.key === "ArrowLeft") {
          e.preventDefault();
          go(-1);
          restartAutoplay();
        } else if (e.key === "ArrowRight") {
          e.preventDefault();
          go(1);
          restartAutoplay();
        }
      },
      true
    );

    root.setAttribute("tabindex", "0");

    root.addEventListener(
      "touchstart",
      function (e) {
        if (!e.changedTouches || !e.changedTouches[0]) return;
        touchStartX = e.changedTouches[0].clientX;
      },
      { passive: true }
    );

    root.addEventListener(
      "touchend",
      function (e) {
        if (touchStartX == null || !e.changedTouches || !e.changedTouches[0]) return;
        let dx = e.changedTouches[0].clientX - touchStartX;
        touchStartX = null;
        if (Math.abs(dx) < 50) return;
        if (dx > 0) go(-1);
        else go(1);
        restartAutoplay();
      },
      { passive: true }
    );

    function stopAutoplay() {
      if (autoplayId != null) {
        clearInterval(autoplayId);
        autoplayId = null;
      }
    }

    function startAutoplay() {
      stopAutoplay();
      if (reduceMotion) return;
      autoplayId = window.setInterval(function () {
        if (!isHomeSectionVisible() || document.hidden) return;
        go(1);
      }, 6000);
    }

    function restartAutoplay() {
      stopAutoplay();
      startAutoplay();
    }

    root.addEventListener("mouseenter", stopAutoplay);
    root.addEventListener("mouseleave", startAutoplay);
    document.addEventListener("visibilitychange", function () {
      if (document.hidden) stopAutoplay();
      else if (isHomeSectionVisible()) startAutoplay();
    });
    window.addEventListener("hashchange", function () {
      if (isHomeSectionVisible()) startAutoplay();
      else stopAutoplay();
    });

    render();
    if (isHomeSectionVisible()) startAutoplay();
  }

