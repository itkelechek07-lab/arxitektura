  function initNewsSlider() {
    let root = $("#news-slider");
    let track = $("#news-slider-track");
    let prev = $("#news-slider-prev");
    let next = $("#news-slider-next");
    let listButtons = $all(".news-list-item");
    if (!root || !track || !prev || !next || !listButtons.length) return;

    let count = $all(".news-slider__slide", root).length;
    let index = 0;
    let timer = null;

    function render() {
      track.style.transform = "translateX(-" + index * 100 + "%)";
      listButtons.forEach(function (btn, i) {
        btn.classList.toggle("is-active", i === index);
      });
    }

    function go(delta) {
      index = (index + delta + count) % count;
      render();
    }

    function goTo(i) {
      index = (i + count) % count;
      render();
    }

    listButtons.forEach(function (btn) {
      btn.addEventListener("click", function () {
        let i = parseInt(btn.getAttribute("data-news-index"), 10);
        if (!isNaN(i)) {
          goTo(i);
          restart();
        }
      });
    });

    prev.addEventListener("click", function () {
      go(-1);
      restart();
    });

    next.addEventListener("click", function () {
      go(1);
      restart();
    });

    function stop() {
      if (timer) {
        clearInterval(timer);
        timer = null;
      }
    }

    function start() {
      stop();
      timer = setInterval(function () {
        if ($("#section-home") && $("#section-home").classList.contains("section--visible")) {
          go(1);
        }
      }, 6000);
    }

    function restart() {
      stop();
      start();
    }

    root.addEventListener("mouseenter", stop);
    root.addEventListener("mouseleave", start);
    render();
    start();
  }

