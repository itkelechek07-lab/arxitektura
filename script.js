  function initNavDropdowns() {
    $all(".nav__item--has-dropdown").forEach(function (item) {
      let toggle = item.querySelector(".nav__dropdown-toggle");
      let menu = item.querySelector(".nav__dropdown");
      if (!toggle || !menu) return;

      toggle.addEventListener("click", function (e) {
        e.preventDefault();
        let willOpen = !item.classList.contains("is-open");
        $all(".nav__item--has-dropdown").forEach(function (other) {
          if (other !== item) {
            other.classList.remove("is-open");
            let ot = other.querySelector(".nav__dropdown-toggle");
            if (ot) ot.setAttribute("aria-expanded", "false");
          }
        });
        item.classList.toggle("is-open", willOpen);
        toggle.setAttribute("aria-expanded", willOpen ? "true" : "false");
      });

      menu.querySelectorAll("a.nav__dropdown-link").forEach(function (link) {
        link.addEventListener("click", function () {
          item.classList.remove("is-open");
          toggle.setAttribute("aria-expanded", "false");
          let targetId = link.getAttribute("data-about-target");
          if (!targetId) return;
          window.setTimeout(function () {
            let target = document.getElementById(targetId);
            if (target) target.scrollIntoView({ behavior: "smooth", block: "start" });
          }, 60);
        });
      });
    });
  }

